import { normalizePhone, normalizeIc, parseJoinedDate, clean } from "../scripts/import/transform";
let fail = 0;
const eq = (name: string, got: unknown, want: unknown) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fail++; console.log(ok ? "ok  " : "FAIL", name, ok ? "" : `got ${JSON.stringify(got)} want ${JSON.stringify(want)}`); };
eq("mobile dashed",        normalizePhone("012-3456789").value, "+60123456789");
eq("mobile 8-digit tail",  normalizePhone("011-12345678").value, "+601112345678");
eq("bracket area code",    normalizePhone("(012) 3456789").value, "+60123456789");
eq("plain digits",         normalizePhone("0123456789").value, "+60123456789");
eq("trailing dot",         normalizePhone("012-3456789.").value, "+60123456789");
eq("country code bracket", normalizePhone("(+60) 123456789").value, "+60123456789");
eq("spaces",               normalizePhone("0 12-345 6789").value, "+60123456789");
eq("landline",             normalizePhone("03-12345678").value, "+60312345678");
eq("two numbers",          normalizePhone("012-3456789 / 013-98765432"), { value: "+60123456789", extra: "+601398765432", invalid: false });
eq("empty",                normalizePhone(null), { value: null, extra: null, invalid: false });
eq("garbage",              normalizePhone("n/a").invalid, true);
eq("IC 12 digits",         normalizeIc("800101015555").value, "800101-01-5555");
eq("IC dashed",            normalizeIc("800101-01-5555").value, "800101-01-5555");
eq("IC zero placeholder",  normalizeIc("0"), { value: null, placeholder: true, needsReview: false });
eq("IC zero as number",    normalizeIc(0).placeholder, true);
eq("IC odd",               normalizeIc("80010-01-5555").needsReview, true);
eq("date ISO",             parseJoinedDate("2004-09-16 00:00:00"), "2004-09-16");
eq("date w/ microseconds", parseJoinedDate("2026-08-29 06:21:21.21686"), "2026-08-29");
eq("date d/m/y",           parseJoinedDate("9/7/2025"), "2025-07-09");
eq("date impossible",      parseJoinedDate("2026-02-31"), null);
eq("date Date object",     parseJoinedDate(new Date("2010-05-06T00:00:00Z")), "2010-05-06");
eq("clean whitespace",     clean("  A   B \n C "), "A B C");
console.log(fail ? `\n${fail} FAILED` : "\nall unit checks passed");
process.exit(fail ? 1 : 0);
